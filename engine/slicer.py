"""Slicer check: slice a passing part with the local ElegooSlicer CLI.

The printability gate checks geometry only. This module gives the slicer's own numbers for
the exact STL files the harness exported: print time, filament, and whether supports were
generated, read from the slicer's 3MF. The 3MF is kept next to the part's other outputs.

It slices and exports, and that is all: the command is built from an allowlist of flags,
and the machine profile's print-host settings are blanked before the slicer sees them.
Sending a job to a printer is always the user's own action, outside this app.
"""
import functools
import json
import os
import re
import shutil
import subprocess
import tempfile
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

from harness.evidence import SLICER_MISSING as MISSING
from library.printer_profiles import PROFILE

ENV = "MAGIC_ELEGOO_SLICER"  # path to the ElegooSlicer executable, if not in a standard place
CANDIDATES = ("/Applications/ElegooSlicer.app/Contents/MacOS/ElegooSlicer",
              str(Path.home() / "Applications/ElegooSlicer.app/Contents/MacOS/ElegooSlicer"))
ALLOWED_FLAGS = frozenset({"--datadir", "--load-settings", "--load-filaments", "--slice", "--orient",
                           "--arrange", "--outputdir", "--export-3mf", "--debug"})
PRINT_HOST_KEYS = re.compile(r"^print_?host")
TIMEOUT = 300  # seconds per design


def find_slicer():
    """The ElegooSlicer executable with its bundled profiles, or None.

    An explicit override that is unusable is None; it never falls back to another install."""
    override = os.environ.get(ENV)
    found = [override] if override else [shutil.which("elegoo-slicer"), *CANDIDATES]
    for path in filter(None, found):
        if Path(path).is_file() and os.access(path, os.X_OK) and profiles_dir(path):
            return Path(path)
    return None


def profiles_dir(executable):
    """The slicer's bundled Elegoo system presets (macOS app bundle layout)."""
    folder = Path(executable).resolve().parent.parent / "Resources" / "profiles" / "Elegoo"
    return folder if folder.is_dir() else None


def without_print_host(machine):
    """A machine profile that names no printer to send to."""
    return {k: ("" if PRINT_HOST_KEYS.match(k) else v) for k, v in machine.items()}


@functools.lru_cache(maxsize=8)
def presets_by_name(folder):
    """Preset name -> file, for one kind of preset (machine, process or filament)."""
    by_name = {}
    for path in Path(folder).rglob("*.json"):
        try:
            by_name.setdefault(json.loads(path.read_text()).get("name"), path)
        except (OSError, ValueError, AttributeError):
            continue
    return by_name


def flatten(vendor, relative):
    """A system preset with its `inherits` chain merged in. The CLI does not resolve the chain."""
    by_name = presets_by_name(str(vendor / Path(relative).parts[0]))
    chain, preset = [], json.loads((vendor / relative).read_text())
    while True:
        chain.append(preset)
        parent = preset.get("inherits")
        if not parent:
            break
        if parent not in by_name or len(chain) > 20:
            raise FileNotFoundError(f"ElegooSlicer preset {parent!r} not found")
        preset = json.loads(by_name[parent].read_text())
    merged = {}
    for preset in reversed(chain):
        merged.update(preset)
    merged.pop("inherits", None)
    return merged


def command(executable, stls, machine, process, filament, outdir, three_mf):
    """The slicer invocation. Only slice-and-export flags; checked against ALLOWED_FLAGS."""
    argv = [str(executable), "--debug", "1", "--datadir", str(Path(outdir).parent / "data"),
            "--load-settings", f"{machine};{process}", "--load-filaments", str(filament),
            "--orient", "0", "--arrange", "1", "--slice", "0",
            "--outputdir", str(outdir), "--export-3mf", three_mf, *map(str, stls)]
    unexpected = {a for a in argv if a.startswith("--")} - ALLOWED_FLAGS
    if unexpected:
        raise ValueError(f"refusing slicer flags outside the allowlist: {sorted(unexpected)}")
    return argv


def read_3mf(path):
    """Print time, filament, supports and layers, as the slicer wrote them into its 3MF."""
    with zipfile.ZipFile(path) as archive:
        plate = ET.fromstring(archive.read("Metadata/slice_info.config")).find("plate")
        gcode = archive.read("Metadata/plate_1.gcode").decode("utf-8", "replace")
    meta = {m.get("key"): m.get("value") for m in plate.findall("metadata")}
    filaments = plate.findall("filament")
    version = re.search(r"generated by (ElegooSlicer [\d.]+)", gcode)
    layers = re.search(r"; total layers count = (\d+)", gcode)
    support_mm = support_extrusion(gcode)
    return {"slicer": version.group(1) if version else "ElegooSlicer",
            "print_seconds": int(float(meta.get("prediction") or 0)),
            "filament_m": round(sum(float(f.get("used_m") or 0) for f in filaments), 2),
            "filament_g": round(sum(float(f.get("used_g") or 0) for f in filaments), 2),
            # slice_info's support_used echoes the setting; the G-code says what was extruded
            "support_used": support_mm > 0,
            "support_filament_mm": support_mm,
            "layers": int(layers.group(1)) if layers else None,
            "outside": meta.get("outside") == "true"}


def support_extrusion(gcode):
    """Filament (mm) extruded in the G-code's support sections."""
    relative, current, last, total = False, "", 0.0, 0.0
    for line in gcode.splitlines():
        if line.startswith(";TYPE:"):
            current = line[6:]
            continue
        code = line.split(";", 1)[0].split()
        if not code:
            continue
        if code[0] in ("M82", "M83"):
            relative = code[0] == "M83"
        elif code[0] == "G92":
            last = next((float(w[1:]) for w in code[1:] if w.startswith("E")), last)
        elif code[0] in ("G0", "G1", "G2", "G3"):
            e = next((float(w[1:]) for w in code[1:] if w.startswith("E")), None)
            if e is None:
                continue
            step = e if relative else e - last
            last = last + e if relative else e
            if step > 0 and "support" in current.lower():
                total += step
    return round(total, 1)


SETUP_ERRORS = (OSError, ValueError, KeyError, AttributeError, zipfile.BadZipFile, ET.ParseError)


def slice_design(stls, out, stem, material, allow_supports, executable=None, timeout=TIMEOUT):
    """Slice the exported STL files of one design onto one plate. Returns the slice result.

    Supports are always enabled, so the slicer says whether the part needs them. The 3MF
    lands at out/<stem>.3mf. result["ran"] is False when the slicer could not be set up (no
    install, missing presets): nothing was judged. result["ok"] is False with
    result["problems"] when the slice failed, put a part outside the printable area, or
    needed supports the brief forbids.
    """
    executable = executable or find_slicer()
    presets = PROFILE["slicer"]
    result = {"ran": False, "ok": False, "slicer": "ElegooSlicer", "material": material,
              "supports_allowed": bool(allow_supports), "problems": [],
              "printer": Path(presets["machine"]).stem, "process": Path(presets["process"]).stem,
              "filament": Path(presets["filaments"][material]).stem}
    vendor = profiles_dir(executable) if executable else None
    if vendor is None:
        result["problems"].append(MISSING if not executable else
                                  f"ElegooSlicer at {executable} has no bundled Elegoo profiles")
        return result
    out = Path(out)
    target = out / f"{stem}.3mf"
    target.unlink(missing_ok=True)
    with tempfile.TemporaryDirectory(prefix="magic-slice-") as tmp:
        tmp = Path(tmp)
        try:
            machine = without_print_host(flatten(vendor, presets["machine"]))
            process = flatten(vendor, presets["process"])
            filament = flatten(vendor, presets["filaments"][material])
        except SETUP_ERRORS as err:
            result["problems"].append(f"ElegooSlicer presets could not be loaded: {err}")
            return result
        process["enable_support"] = "1"
        files = {}
        for name, data in (("machine", machine), ("process", process), ("filament", filament)):
            files[name] = tmp / f"{name}.json"
            files[name].write_text(json.dumps(data, indent=1))
        sliced = tmp / "out"
        sliced.mkdir()
        argv = command(executable, stls, files["machine"], files["process"], files["filament"],
                       sliced, target.name)
        result["ran"] = True
        try:
            done = subprocess.run(argv, cwd=tmp, capture_output=True, text=True, timeout=timeout)
        except subprocess.TimeoutExpired:
            result["problems"].append(f"ElegooSlicer did not finish within {timeout} s")
            return result
        produced = sliced / target.name
        if done.returncode or not produced.is_file():
            errors = [line for line in (done.stdout + done.stderr).splitlines()
                      if "[error]" in line and "shader" not in line.lower()]
            result["problems"].append(f"ElegooSlicer failed (exit {done.returncode}): "
                                      + (errors[-1].split("]")[-1].strip() if errors else "no 3MF written"))
            return result
        out.mkdir(parents=True, exist_ok=True)
        shutil.move(produced, target)
    result["three_mf"] = target.name
    try:
        result.update(read_3mf(target))
    except SETUP_ERRORS as err:
        result["problems"].append(f"the slicer's 3MF could not be read: {err}")
        return result
    if result["outside"]:
        result["problems"].append("a part lies outside the printable area")
    if result["support_used"] and not allow_supports:
        result["problems"].append(f"the slicer needs supports ({result['support_filament_mm']:.0f} mm of "
                                  "filament) but the brief does not allow them")
    result["ok"] = not result["problems"]
    return result
